lines.append('import { useEffect, useState } from "react";')
lines.append('import { useParams, useRouter } from "next/navigation";')
lines.append('import { supabase } from "@/lib/supabaseClient";')
lines.append('export default function MasterOrderPage() {')
lines.append('  const params = useParams();')
lines.append('  const router = useRouter();')
lines.append('  const orderId = Number(params.id);')
lines.append('  const [order, setOrder] = useState<any>(null);')
lines.append('  const [services, setServices] = useState<any[]>([]);')
lines.append('  const [inventory, setInventory] = useState<any[]>([]);')
lines.append('  const [allServices, setAllServices] = useState<any[]>([]);')
lines.append('  const [allInventory, setAllInventory] = useState<any[]>([]);')
lines.append('  const [loading, setLoading] = useState(true);')
lines.append('  const [showSvcModal, setShowSvcModal] = useState(false);')
lines.append('  const [showInvModal, setShowInvModal] = useState(false);')
lines.append('  const [selSvcId, setSelSvcId] = useState("");')
lines.append('  const [selSvcQty, setSelSvcQty] = useState(1);')
lines.append('  const [selInvId, setSelInvId] = useState("");')
lines.append('  const [selInvQty, setSelInvQty] = useState(1);')
lines.append('  const [svcSearch, setSvcSearch] = useState("");')
lines.append('  const [invSearch, setInvSearch] = useState("");')
lines.append('  useEffect(() => { if (orderId) loadData(); }, [orderId]);')
lines.append('  const loadData = async () => {')
lines.append('    setLoading(true);')
lines.append('    const { data: o } = await supabase.from("orders").select("*").eq("id", orderId).single();')
