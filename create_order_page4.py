lines.append('    setInventory(iv || []);')
lines.append('    if (o?.company_id) {')
lines.append('      const { data: as2 } = await supabase.from("services").select("*").eq("company_id", o.company_id);')
lines.append('      setAllServices(as2 || []);')
lines.append('      const { data: ai } = await supabase.from("inventory").select("*").eq("company_id", o.company_id);')
lines.append('      setAllInventory(ai || []);')
lines.append('    }')
lines.append('    setLoading(false);')
lines.append('  };')
lines.append('  const addSvc = async () => {')
lines.append('    if (!selSvcId) return;')
lines.append('    const s = allServices.find(x => x.id === Number(selSvcId));')
lines.append('    if (!s) return;')
lines.append('    await supabase.from("order_services").insert({ order_id: orderId, service_id: Number(selSvcId), quantity: selSvcQty, price: s.price || 0, company_id: order.company_id });')
lines.append('    setShowSvcModal(false); setSelSvcId(""); setSelSvcQty(1); setSvcSearch("");')
lines.append('    loadData();')
lines.append('  };')
lines.append('  const addInv = async () => {')
lines.append('    if (!selInvId) return;')
lines.append('    const i = allInventory.find(x => x.id === Number(selInvId));')
lines.append('    if (!i) return;')
lines.append('    await supabase.from("order_inventory").insert({ order_id: orderId, inventory_id: Number(selInvId), quantity: selInvQty, price: i.sale_price || 0, company_id: order.company_id });')
lines.append('    setShowInvModal(false); setSelInvId(""); setSelInvQty(1); setInvSearch("");')
lines.append('    loadData();')
lines.append('  };')
lines.append('  const remSvc = async (id: number) => {')
lines.append('    if (order?.status === "completed") return;')
lines.append('    await supabase.from("order_services").delete().eq("id", id);')
lines.append('    loadData();')
lines.append('  };')
lines.append('  const remInv = async (id: number) => {')
lines.append('    if (order?.status === "completed") return;')
lines.append('    await supabase.from("order_inventory").delete().eq("id", id);')
lines.append('    loadData();')
lines.append('  };')
lines.append('  const acceptOrder = async () => {')
lines.append('    await supabase.from("orders").update({ status: "in_progress" }).eq("id", orderId);')
lines.append('    loadData();')
lines.append('  };')
lines.append('  const completeOrder = async () => {')
lines.append('    await supabase.from("orders").update({ status: "completed" }).eq("id", orderId);')
lines.append('    loadData();')
lines.append('  };')
lines.append('  const isDone = order?.status === "completed";')
lines.append('  const fSvc = allServices.filter(s => s.name?.toLowerCase().includes(svcSearch.toLowerCase()));')
lines.append('  const fInv = allInventory.filter(i => i.name?.toLowerCase().includes(invSearch.toLowerCase()));')
lines.append('  if (loading) { return (<div className="p-8 text-center">Loading...</div>); }')
lines.append('  if (!order) { return (<div className="p-8 text-center">Not found</div>); }')
lines.append('  return (')
lines.append('    <div className="max-w-3xl mx-auto p-4">')
lines.append('      <button onClick={() => router.back()} className="mb-4 text-blue-600 hover:underline">Back</button>')
lines.append('      <h1 className="text-2xl font-bold mb-4">Order #{order.id}</h1>')
lines.append('      <div className="bg-white rounded-lg shadow p-4 mb-4">')
lines.append('        <p><strong>Org:</strong> {order.organization_name || "-"}</p>')
lines.append('        <p><strong>Contact:</strong> {order.contact_name || "-"}</p>')
lines.append('        <p><strong>Phone:</strong> {order.contact_phone || "-"}</p>')
lines.append('        <p><strong>Addr:</strong> {order.address || "-"}</p>')
lines.append('        <p><strong>Status:</strong> {order.status}</p>')
lines.append('      </div>')
lines.append('      <div className="bg-white rounded-lg shadow p-4 mb-4">')
lines.append('        <div className="flex justify-between items-center mb-2">')
lines.append('          <h2 className="text-lg font-semibold">Services</h2>')
lines.append('          {!isDone && <button onClick={() => setShowSvcModal(true)} className="bg-blue-600 text-white px-3 py-1 rounded text-sm">+ Add</button>}')
lines.append('        </div>')
lines.append('        {services.length === 0 ? <p className="text-gray-500">No services</p> : (')
lines.append('          <ul className="space-y-2">{services.map(s => (')
lines.append('            <li key={s.id} className="flex justify-between items-center bg-gray-50 p-2 rounded">')
lines.append('              <span>{s.services?.name || "?"} &times; {s.quantity}</span>')
lines.append('              {!isDone && <button onClick={() => remSvc(s.id)} className="text-red-600 text-sm">Del</button>}')
lines.append('            </li>))}</ul>)')
lines.append('      </div>')
lines.append('      <div className="bg-white rounded-lg shadow p-4 mb-4">')
lines.append('        <div className="flex justify-between items-center mb-2">')
lines.append('          <h2 className="text-lg font-semibold">Items</h2>')
lines.append('          {!isDone && <button onClick={() => setShowInvModal(true)} className="bg-blue-600 text-white px-3 py-1 rounded text-sm">+ Add</button>}')
lines.append('        </div>')
lines.append('        {inventory.length === 0 ? <p className="text-gray-500">No items</p> : (')
lines.append('          <ul className="space-y-2">{inventory.map(i => (')
lines.append('            <li key={i.id} className="flex justify-between items-center bg-gray-50 p-2 rounded">')
lines.append('              <span>{i.inventory?.name || "?"} &times; {i.quantity}</span>')
lines.append('              {!isDone && <button onClick={() => remInv(i.id)} className="text-red-600 text-sm">Del</button>}')
lines.append('            </li>))}</ul>)')
lines.append('      </div>')
lines.append('      <div className="flex gap-2">')
lines.append('        {order.status === "assigned" && <button onClick={acceptOrder} className="flex-1 bg-blue-600 text-white py-3 rounded-lg">Accept</button>}')
lines.append('        {order.status === "in_progress" && <button onClick={completeOrder} className="flex-1 bg-green-600 text-white py-3 rounded-lg">Complete</button>}')
lines.append('      </div>')
lines.append('      {showSvcModal && (')
lines.append('        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">')
lines.append('          <div className="bg-white rounded-lg p-6 w-96 max-h-[80vh] overflow-y-auto">')
lines.append('            <h3 className="text-lg font-semibold mb-3">Add Service</h3>')
