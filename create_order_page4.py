lines.append('            <div className="flex gap-2">')
lines.append('              <button onClick={addSvc} className="flex-1 bg-blue-600 text-white py-2 rounded">Add</button>')
lines.append('              <button onClick={() => setShowSvcModal(false)} className="flex-1 bg-gray-300 py-2 rounded">Cancel</button>')
lines.append('            </div></div></div>)')
lines.append('      }')
lines.append('      {showInvModal && (')
lines.append('        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">')
lines.append('          <div className="bg-white rounded-lg p-6 w-96 max-h-[80vh] overflow-y-auto">')
lines.append('            <h3 className="text-lg font-semibold mb-3">Add Item</h3>')
lines.append('            <input type="text" placeholder="Search..." value={invSearch} onChange={e => setInvSearch(e.target.value)} className="w-full border rounded px-3 py-2 mb-3" />')
lines.append('            <select value={selInvId} onChange={e => setSelInvId(e.target.value)} className="w-full border rounded px-3 py-2 mb-3">')
lines.append('              <option value="">Select</option>')
lines.append('              {fInv.map(i => <option key={i.id} value={i.id}>{i.name}</option>)}')
lines.append('            </select>')
lines.append('            <input type="number" min="1" value={selInvQty} onChange={e => setSelInvQty(Number(e.target.value))} className="w-full border rounded px-3 py-2 mb-3" />')
lines.append('            <div className="flex gap-2">')
lines.append('              <button onClick={addInv} className="flex-1 bg-blue-600 text-white py-2 rounded">Add</button>')
lines.append('              <button onClick={() => setShowInvModal(false)} className="flex-1 bg-gray-300 py-2 rounded">Cancel</button>')
lines.append('            </div></div></div>)')
lines.append('      }')
lines.append('    </div>')
lines.append('  );')
lines.append('}')

